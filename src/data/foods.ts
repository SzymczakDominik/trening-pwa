export const FOOD_CATEGORIES = Object.keys(RAW);

function parse(cat: string, line: string, i: number): Food {
  const [name, kcal, p, c, f, portion] = line.split('|');
  const food: Food = { id: `b-${FOOD_CATEGORIES.indexOf(cat)}-${i}`, name, cat, kcal: +kcal, p: +p, c: +c, f: +f };
  if (portion) { const [label, g] = portion.split('='); food.portion = { label, g: +g }; }
  return food;
}

export const BUILTIN_FOODS: Food[] = Object.entries(RAW).flatMap(([cat, lines]) => lines.map((l, i) => parse(cat, l, i)));
